"""Builds the keyboard's base dictionaries (core/src/main/resources/dictionary/<lang>.txt).

    pip install spylls
    python3 tools/dictionary/build_base.py <work-dir>

Each list is the hand-picked words in tools/dictionary/curated/<lang>.txt, followed by the most frequent
words of the language that pass three filters:

* frequency: OpenSubtitles 2018 word counts from https://github.com/hermitdave/FrequencyWords
  (content licensed CC BY-SA 4.0, so the generated lists are CC BY-SA 4.0 as well);
* spelling: the word must be accepted by the LibreOffice Hunspell dictionary of that language
  (https://github.com/LibreOffice/dictionaries). This drops the Russian words that fill Ukrainian
  subtitles, names and typos;
* alphabet and a short list of rude word stems.

It also writes <lang>_known.txt: every word of the 50k frequency list that passes the spelling and
alphabet checks (rude words included). Autocorrect leaves those alone even though they are too rare to
be suggested, so a correct but less common word form is never "fixed" into a frequent one.

The work dir keeps the downloads, so a second run is offline.
"""
import re
import sys
import urllib.request
from pathlib import Path

from spylls.hunspell import Dictionary

TOTAL = 10_000
ROOT = Path(__file__).resolve().parents[2]
WORK = Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/offkey-dictionary")

FREQ = "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/{0}/{0}_50k.txt"
HUNSPELL = "https://raw.githubusercontent.com/LibreOffice/dictionaries/master/{}"
LANGUAGES = {
    "uk": ("uk_UA/uk_UA", r"[абвгґдеєжзиіїйклмнопрстуфхцчшщьюя'ʼ-]+"),
    "pl": ("pl_PL/pl_PL", r"[a-ząćęłńóśźż-]+"),
    "en": ("en/en_US", r"[a-z'-]+"),
}
RUDE = {
    "uk": ["бля", "хуй", "хуя", "хує", "пизд", "єба", "їба", "еба", "ебл", "сука", "суки", "мудак", "курв", "підар", "підор", "шлюх", "гандон"],
    "pl": ["kurw", "chuj", "huj", "pierdol", "jeb", "pizd", "cipa", "cipk", "dziwk", "pedał", "pedal", "kutas", "suka", "suki", "fiut"],
    "en": ["fuck", "shit", "bitch", "cunt", "dick", "pussy", "cock", "asshole", "bastard", "whore", "slut", "nigg", "fag", "twat", "wank"],
}


def fetch(url, path):
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        urllib.request.urlretrieve(url, path)
    return path


def build(lang):
    dic_path, alphabet = LANGUAGES[lang]
    freq = fetch(FREQ.format(lang), WORK / f"{lang}_50k.txt")
    name = Path(dic_path).name
    fetch(HUNSPELL.format(dic_path + ".aff"), WORK / f"{name}.aff")
    fetch(HUNSPELL.format(dic_path + ".dic"), WORK / f"{name}.dic")
    speller = Dictionary.from_files(str(WORK / name))
    pattern = re.compile(alphabet)

    curated_file = ROOT / "tools/dictionary/curated" / f"{lang}.txt"
    header = [l for l in curated_file.read_text(encoding="utf-8").splitlines() if l.startswith("#")]
    curated = [l.strip() for l in curated_file.read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#")]
    seen = {w.lower() for w in curated}
    words = list(curated)
    known = []
    for line in freq.read_text(encoding="utf-8").splitlines():
        word = line.split(" ")[0].strip().lower()
        if len(word) < 2 or not pattern.fullmatch(word) or not speller.lookup(word):
            continue
        known.append(word)
        if len(words) >= TOTAL or word in seen or any(stem in word for stem in RUDE[lang]):
            continue
        seen.add(word)
        words.append(word)

    out = ROOT / "core/src/main/resources/dictionary" / f"{lang}.txt"
    out.parent.mkdir(parents=True, exist_ok=True)
    notice = [
        "# Generated by tools/dictionary/build_base.py: hand-picked words, then the most frequent words of",
        "# OpenSubtitles 2018 (hermitdave/FrequencyWords, CC BY-SA 4.0) accepted by the LibreOffice Hunspell",
        "# dictionary. This list is licensed CC BY-SA 4.0.",
    ]
    out.write_text("\n".join(notice + header[:1] + words) + "\n", encoding="utf-8")
    known = [w for w in dict.fromkeys(known) if w not in seen]
    known_out = out.parent / f"{lang}_known.txt"
    known_out.write_text("\n".join(notice[:2] + ["# Valid words outside the base list, for autocorrect only. CC BY-SA 4.0."] + known) + "\n", encoding="utf-8")
    print(f"{lang}: {len(words)} words ({len(curated)} hand-picked), {len(known)} more known")


if __name__ == "__main__":
    for lang in LANGUAGES:
        build(lang)
