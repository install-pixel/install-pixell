"""Builds the next-word lists (core/src/main/resources/dictionary/<lang>_next.txt).

    python3 tools/dictionary/build_bigrams.py <work-dir>

For every common word, the words that most often follow it in the Tatoeba sentences of the language
(https://tatoeba.org, CC BY 2.0 FR; downloads.tatoeba.org/exports/per_language). Only words of the base
list (<lang>.txt, built by build_base.py) are kept on both sides, so the suggestions are spelled right and
never rude. A line is `word<TAB>next next next…`, most frequent first.

The work dir keeps the downloads, so a second run is offline. Run in CI (offline-keyboard-bigrams.yml):
the download host is not reachable from every machine.
"""
import bz2
import collections
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WORK = Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/offkey-bigrams")
URL = "https://downloads.tatoeba.org/exports/per_language/{0}/{0}_sentences.tsv.bz2"
LANGUAGES = {"uk": "ukr", "pl": "pol", "en": "eng"}
WORD = {
    "uk": re.compile(r"[абвгґдеєжзиіїйклмнопрстуфхцчшщьюя'ʼ’-]+"),
    "pl": re.compile(r"[a-ząćęłńóśźż-]+"),
    "en": re.compile(r"[a-z'’-]+"),
}
# A sentence breaks the chain at these marks: "дякую. А ти" gives no pair "дякую → а".
BREAK = re.compile(r"[.!?;:…()\[\]\"«»„“”]")
PER_WORD = 5
MIN_COUNT = 2
MAX_WORDS = 12000


def fetch(url, path):
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        urllib.request.urlretrieve(url, path)
    return path


def base_words(lang):
    path = ROOT / "core/src/main/resources/dictionary" / f"{lang}.txt"
    return [l.strip().lower() for l in path.read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#")]


def build(lang):
    archive = fetch(URL.format(LANGUAGES[lang]), WORK / f"{LANGUAGES[lang]}_sentences.tsv.bz2")
    known = base_words(lang)
    rank = {w: i for i, w in enumerate(known)}
    pattern = WORD[lang]
    pairs = collections.defaultdict(collections.Counter)
    with bz2.open(archive, "rt", encoding="utf-8") as f:
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) < 3:
                continue
            for chunk in BREAK.split(parts[2].lower().replace("ʼ", "'").replace("’", "'")):
                words = [w for w in (m.group(0).strip("-'") for m in pattern.finditer(chunk)) if w]
                for a, b in zip(words, words[1:]):
                    if a in rank and b in rank:
                        pairs[a][b] += 1
    # The most common words first, so the app can stop reading early if it ever needs to.
    lines = []
    for word in sorted(pairs, key=lambda w: rank[w]):
        best = [w for w, c in pairs[word].most_common(PER_WORD * 2) if c >= MIN_COUNT][:PER_WORD]
        if best:
            lines.append(word + "\t" + " ".join(best))
        if len(lines) >= MAX_WORDS:
            break
    out = ROOT / "core/src/main/resources/dictionary" / f"{lang}_next.txt"
    notice = [
        "# Generated by tools/dictionary/build_bigrams.py: the words that most often follow a word in the",
        "# Tatoeba sentences (https://tatoeba.org, CC BY 2.0 FR), limited to the base list. CC BY 2.0 FR.",
    ]
    out.write_text("\n".join(notice + lines) + "\n", encoding="utf-8")
    print(f"{lang}: {len(lines)} words with next words")


if __name__ == "__main__":
    for lang in LANGUAGES:
        build(lang)
