"""Builds core/src/main/resources/dictionary/uk_apostrophe.txt: how Ukrainian words with an apostrophe begin,
so the keyboard can put back an apostrophe that was not typed ("мясо" -> "м'ясо", "обєкт" -> "об'єкт").

    python3 tools/dictionary/build_apostrophes.py [uk_UA.dic]

Source: the LibreOffice Ukrainian Hunspell dictionary (dict_uk, MPL 1.1). Each entry is a word's beginning up
to and including the apostrophe and at most two letters after it ("м'яс", "об'єк", "здоров'я"): word endings
change, the part around the apostrophe does not. Names (capitalised) are left out.
"""
import re, sys, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
URL = "https://raw.githubusercontent.com/LibreOffice/dictionaries/master/uk_UA/uk_UA.dic"

path = Path(sys.argv[1]) if len(sys.argv) > 1 else None
text = path.read_text(encoding="utf-8") if path else urllib.request.urlopen(URL).read().decode("utf-8")
word = re.compile(r"[абвгґдеєжзиіїйклмнопрстуфхцчшщьюя'-]+")
keys = set()
for line in text.splitlines()[1:]:
    lemma = line.split("/")[0].strip()
    if "'" not in lemma or not word.fullmatch(lemma):
        continue
    i = lemma.index("'")
    keys.add(lemma[:i + 3])
out = ROOT / "core/src/main/resources/dictionary/uk_apostrophe.txt"
out.write_text(
    "# Generated by tools/dictionary/build_apostrophes.py from the LibreOffice Ukrainian Hunspell dictionary\n"
    "# (dict_uk, https://github.com/brown-uk/dict_uk, MPL 1.1): beginnings of words with an apostrophe.\n"
    + "\n".join(sorted(keys)) + "\n",
    encoding="utf-8",
)
print(len(keys), "beginnings")
